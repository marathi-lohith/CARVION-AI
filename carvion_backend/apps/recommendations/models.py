import datetime
from mongoengine import Document, StringField, DictField, DateTimeField, ReferenceField, IntField
from apps.authentication.models import User

class JobCache(Document):
    """
    MongoEngine Job Cache Document.
    Caches job results queried via JSearch API.
    MongoDB TTL index automatically evicts documents on expires_at.
    """
    meta = {
        'collection': 'job_caches',
        'indexes': [
            'query',
            {'fields': ['expires_at'], 'expireAfterSeconds': 0}  # TTL Index
        ]
    }

    query = StringField(required=True, unique=True)
    payload = DictField(default=dict)
    created_at = DateTimeField(default=datetime.datetime.utcnow)
    expires_at = DateTimeField(required=True)


