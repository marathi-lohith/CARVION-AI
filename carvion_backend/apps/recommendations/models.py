class PlatformStatsCounter(Document):
    """
    MongoEngine PlatformStatsCounter Document.
    Tracks global lifetime platform statistics.
    """
    meta = {
        'collection': 'platform_stats_counters'
    }
    total_resume_uploads = IntField(default=0)
    total_ats_reports_generated = IntField(default=0)
    total_cover_letters_generated = IntField(default=0)
    total_interviews_completed = IntField(default=0)
    total_career_insights_generated = IntField(default=0)
    total_learning_roadmaps = IntField(default=0)

def ensure_platform_stats_initialized():
    try:
        if PlatformStatsCounter.objects.count() == 0:
            from apps.resumes.models import Resume, CoverLetter
            from apps.recommendations.models import CareerInsightHistory
            from apps.learning.models import Roadmap
            from apps.assessments.models import Scorecard
            
            resumes_count = Resume.objects.count()
            cover_letters_count = CoverLetter.objects.count()
            roadmaps_count = Roadmap.objects.count()
            career_insights_count = CareerInsightHistory.objects.count()
            scorecards_count = Scorecard.objects.count()
            ats_reports_count = resumes_count
            
            col = PlatformStatsCounter._get_collection()
            col.update_one(
                {},
                {"$setOnInsert": {
                    "total_resume_uploads": resumes_count,
                    "total_ats_reports_generated": ats_reports_count,
                    "total_cover_letters_generated": cover_letters_count,
                    "total_interviews_completed": scorecards_count,
                    "total_career_insights_generated": career_insights_count,
                    "total_learning_roadmaps": roadmaps_count
                }},
                upsert=True
            )
    except Exception as e:
        import logging
        logger = logging.getLogger("carvion.api")
        logger.error(f"Failed to initialize platform stats counter: {str(e)}")


def increment_lifetime_stat(stat_name):
    try:
        ensure_platform_stats_initialized()
        PlatformStatsCounter.objects.update_one(upsert=True, **{f"inc__{stat_name}": 1})
    except Exception as e:
        import logging
        logger = logging.getLogger("carvion.api")
        logger.error(f"Failed to increment lifetime stat {stat_name}: {str(e)}")


